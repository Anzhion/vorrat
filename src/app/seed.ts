export function seedInventory(): Inventory {
  let n = 0;
  const items: Item[] = [];
  for (const [locationId, list] of Object.entries(rows)) {
    for (const [name, amount, target, aisleId, opts] of list) {
      items.push({ id: `s${++n}`, name, locationId, aisleId, amount, target, ...opts });
    }
  }
  return {
    version: 1,
    locations: locations.map(([id, name]) => ({ id, name })),
    aisles: aisles.map(([id, name]) => ({ id, name })),
    combos: [
      { id: 'nudeln', name: 'Nudeln (Farfalle, Spaghetti, Bandnudeln …)', target: 2 },
      { id: 'melone', name: 'Melone oder Ananas', target: 1 },
    ],
    items,
    cart: [],
    updatedAt: Date.now(),
  };
}
